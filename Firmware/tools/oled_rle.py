"""Convert 1-bit bitmaps (Adafruit drawBitmap layout) into run-length coded SSD1306 pages.

The A-RYTH-MATIK animation firmware draw their frames straight into the display buffer from this
format: it takes about a third of the flash of the plain bitmaps and needs no per-pixel work.

Usage:
  oled_rle.py SOURCE POINTER_ARRAY PREFIX WIDTH HEIGHT YOFF OUT.h

  SOURCE         C file with the bitmaps as `const unsigned char NAME[] PROGMEM = { 0x.., ... };`
                 (rows of WIDTH pixels, MSB = leftmost pixel, rows padded to whole bytes) and a
                 pointer array listing them in frame order: `const unsigned char* NAME[] = {...}`.
  POINTER_ARRAY  name of that pointer array (gives the frame order)
  PREFIX         prefix of the generated names, e.g. CAT -> CAT_W, CAT_PAGES, CAT_RLE, CAT_OFS
  WIDTH HEIGHT   bitmap size in pixels
  YOFF           empty rows added above the bitmap, so it starts on a display page (y = 8 * n)
                 when it is drawn at y = YOFF on the screen; 0 if it already starts on a page

Generated format (also written as a comment into OUT.h):
  Each frame is PAGES pages of W column bytes (SSD1306 layout: bit 0 = top pixel of the page),
  page by page, left to right. It is run-length coded: a control byte c < 128 is followed by
  c + 1 literal bytes; c >= 128 means the next byte repeated c - 125 times (3..130).
  Frame n is CAT_RLE[CAT_OFS[n]] .. CAT_RLE[CAT_OFS[n + 1] - 1].
"""
import os
import re
import sys


def parse(src, pointer_array, w, h):
    text = open(src, encoding='utf-8', errors='replace').read()
    text = re.sub(r'//[^\n]*', '', text)
    arrays = {}
    for name, body in re.findall(r'const\s+unsigned\s+char\s+(\w+)\s*\[\s*\]\s*PROGMEM\s*=\s*\{([^}]*)\}', text):
        arrays[name] = [int(v, 16) for v in re.findall(r'0x([0-9a-fA-F]{1,2})', body)]
    m = re.search(r'const\s+unsigned\s+char\s*\*\s*(?:const\s+)?' + re.escape(pointer_array)
                  + r'\s*\[[^\]]*\]\s*(?:PROGMEM\s*)?=\s*\{([^}]*)\}', text)
    if not m:
        sys.exit('pointer array %s not found' % pointer_array)
    order = re.findall(r'\w+', m.group(1))
    need = (w + 7) // 8 * h
    frames = []
    for name in order:
        if name not in arrays:
            sys.exit('bitmap %s not found' % name)
        if len(arrays[name]) != need:
            sys.exit('bitmap %s has %d bytes, expected %d for %dx%d' % (name, len(arrays[name]), need, w, h))
        frames.append(arrays[name])
    return order, frames


def to_pages(vals, w, h, yoff):
    row_bytes = (w + 7) // 8
    rows = h + yoff
    pages = (rows + 7) // 8
    out = []
    for p in range(pages):
        for x in range(w):
            b = 0
            for bit in range(8):
                y = p * 8 + bit - yoff
                if 0 <= y < h and vals[y * row_bytes + x // 8] & (0x80 >> (x % 8)):
                    b |= 1 << bit
            out.append(b)
    return pages, out


def rle(data):
    out, i, n = [], 0, len(data)
    while i < n:
        j = i
        while j + 1 < n and data[j + 1] == data[i] and j - i < 129:
            j += 1
        if j - i + 1 >= 3:
            out += [j - i + 1 + 125, data[i]]
            i = j + 1
            continue
        k = i
        while k < n and k - i < 128:
            if k + 2 < n and data[k] == data[k + 1] == data[k + 2]:
                break
            k += 1
        out += [k - i - 1] + data[i:k]
        i = k
    return out


def unrle(code):
    out, i = [], 0
    while i < len(code):
        c = code[i]
        if c < 128:
            out += code[i + 1:i + 2 + c]
            i += 2 + c
        else:
            out += [code[i + 1]] * (c - 125)
            i += 2
    return out


def main():
    if len(sys.argv) != 8:
        sys.exit(__doc__)
    src, pointer_array, prefix = sys.argv[1:4]
    w, h, yoff = int(sys.argv[4]), int(sys.argv[5]), int(sys.argv[6])
    out_path = sys.argv[7]
    order, frames = parse(src, pointer_array, w, h)
    blob, ofs, raw = [], [], 0
    pages = 0
    for vals in frames:
        pages, pg = to_pages(vals, w, h, yoff)
        code = rle(pg)
        assert unrle(code) == pg
        ofs.append(len(blob))
        blob += code
        raw += len(vals)
    ofs.append(len(blob))
    lines = [
        '// Generated by Firmware/tools/oled_rle.py from %s - do not edit, regenerate instead:' % os.path.basename(src),
        '//   py -3 ../tools/oled_rle.py %s %s %s %d %d %d %s' % (
            os.path.basename(src), pointer_array, prefix, w, h, yoff, os.path.basename(out_path)),
        '// %d frames of %dx%d pixels (%d empty rows on top): %d bytes instead of %d.' % (
            len(frames), w, h, yoff, len(blob) + 2 * len(ofs), raw),
        '// Each frame = %s_PAGES pages of %s_W column bytes (SSD1306 layout: bit 0 = top pixel of' % (prefix, prefix),
        '// the page), page by page, left to right, run-length coded: a control byte c < 128 is',
        '// followed by c + 1 literal bytes; c >= 128 = the next byte repeated c - 125 times (3..130).',
        '// Frame n = %s_RLE[%s_OFS[n]] .. %s_RLE[%s_OFS[n + 1] - 1].' % (prefix, prefix, prefix, prefix),
        '#pragma once',
        '#include <avr/pgmspace.h>',
        '',
        '#define %s_W %d' % (prefix, w),
        '#define %s_PAGES %d' % (prefix, pages),
        '#define %s_FRAMES %d' % (prefix, len(frames)),
        '',
        'const uint8_t %s_RLE[] PROGMEM = {' % prefix,
    ]
    for i in range(0, len(blob), 16):
        lines.append('  ' + ', '.join('0x%02x' % b for b in blob[i:i + 16]) + ',')
    lines += ['};', '', 'const uint16_t %s_OFS[%s_FRAMES + 1] PROGMEM = {' % (prefix, prefix)]
    for i in range(0, len(ofs), 12):
        lines.append('  ' + ', '.join(str(v) for v in ofs[i:i + 12]) + ',')
    lines += ['};', '']
    open(out_path, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
    print('%s: %d frames, %d pages x %d columns, %d -> %d bytes (+%d offsets)' % (
        out_path, len(frames), pages, w, raw, len(blob), 2 * len(ofs)))


if __name__ == '__main__':
    main()
